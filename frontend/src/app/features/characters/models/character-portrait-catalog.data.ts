export function resolveCharacterGlbUrl(url: string | null | undefined): string | null {
  if (!url) return null;
  if (url.endsWith('.glb')) return url;
  const match = /(obj-[a-f0-9]{16})/i.exec(url);
  if (match) {
    return `/assets/object-library/models/${match[1]}.glb`;
  }
  const preset = CHARACTER_3D_PORTRAIT_PRESETS.find(
    (p) => p.imageUrl === url || p.glbUrl === url,
  );
  return preset?.glbUrl ?? null;
}
